/*
	Lexicon stored in flash (wordbank.bin). The ESP32 XS heap is 4928 slots
	and 77KB; materializing the lists as JS arrays aborts before the first
	frame, so the backlight stays off. Reads below copy only a few bytes.
	Generated by scripts/gen-wordbank.mjs. Do not edit the binary.
*/

import Resource from "Resource";

const BANK_STRIDE = 12;
const LEX_STRIDE = 8;
const HEADER = 16;
const MAGIC = 0x314b4257;

type Bin = InstanceType<typeof Resource>;

type BankFile = {
	res: Bin;
	banks: number;
	lex: number;
	lexAt: number;
};

function u16(b: Uint8Array): number {
	return b[0] | (b[1] << 8);
}

function u32(b: Uint8Array): number {
	return (b[0] | (b[1] << 8) | (b[2] << 16) | (b[3] << 24)) >>> 0;
}

function read(res: Bin, off: number, len: number): Uint8Array {
	return new Uint8Array(res.slice(off, off + len));
}

function load(): BankFile | null {
	try {
		const res = new Resource("wordbank.bin");
		const head = read(res, 0, HEADER);
		if (u32(head) !== MAGIC)
			return null;
		return {
			res,
			banks: u16(head.subarray(4, 6)),
			lex: u16(head.subarray(6, 8)),
			lexAt: u32(head.subarray(8, 12)),
		};
	}
	catch {
		return null;
	}
}

/*
	xsl preloads this module and runs its top level. Native constructors are
	stubs there ("link: unavailable function"), and the resulting slots are
	what the device runs. Opening the resource at import time freezes an
	empty bank into the image, so the screen stays on 无词库. Open on first use.
*/
let loaded: BankFile | null | undefined;

function openFile(): BankFile | null {
	if (loaded === undefined)
		loaded = load();
	return loaded;
}

function text(off: number, len: number): string {
	const file = openFile();
	if (!file || len <= 0)
		return "";
	return String.fromArrayBuffer(file.res.slice(off, off + len));
}

export function storedBankCount(): number {
	const file = openFile();
	return file ? file.banks : 0;
}

export function storedBankName(bank: number): string {
	const file = openFile();
	if (!file || bank < 0 || bank >= file.banks)
		return "";
	const o = HEADER + bank * BANK_STRIDE;
	const rec = read(file.res, o, BANK_STRIDE);
	return text(u32(rec.subarray(8, 12)), u16(rec.subarray(6, 8)));
}

export function storedBankSize(bank: number): number {
	const file = openFile();
	if (!file || bank < 0 || bank >= file.banks)
		return 0;
	return u16(read(file.res, HEADER + bank * BANK_STRIDE + 4, 2));
}

export function storedLexId(bank: number, index: number): number {
	const file = openFile();
	if (!file || bank < 0 || bank >= file.banks)
		return 0;
	const o = HEADER + bank * BANK_STRIDE;
	const rec = read(file.res, o, 8);
	const n = u16(rec.subarray(4, 6));
	if (n <= 0)
		return 0;
	let i = index | 0;
	if (i < 0)
		i = 0;
	if (i >= n)
		i = i % n;
	return u16(read(file.res, u32(rec.subarray(0, 4)) + i * 2, 2));
}

export function storedLexWord(id: number): string {
	const file = openFile();
	if (!file || id < 0 || id >= file.lex)
		return "";
	const rec = read(file.res, file.lexAt + id * LEX_STRIDE, 6);
	return text(u32(rec.subarray(0, 4)), u16(rec.subarray(4, 6)));
}
