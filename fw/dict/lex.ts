/*
	Lookup lexicon on cadv/dict/lex.bin. Not opened at import: the image
	link runs this module on the host, where the file natives are stubs.
	Generated by scripts/gen-wordbank.mjs. Do not edit the binary.

	Header 16: magic u32 'WDLX', version u16 = 1, count u16, indexAt u32, blobAt u32.
	Record stride 32, sorted by headword: 16 ASCII bytes, wordLen u8, glossLen u8,
	phoneLen u8, pad u8, glossOff u32, phoneOff u32, pad u32.
	Gloss text is part of speech, then the meaning (`n. 名字`), when a pos exists.
	Prefix end is the lower bound of the successor. 'az' -> 'b'. A prefix of
	only z has no successor; the end is count. Same rules as verifyLex.
*/

import { CardReader, closeQuiet, openCardDir, u16, u32, type ByteSource } from "cardfs";

const STRIDE = 32;
const HEADER = 16;
const MAGIC = 0x584c4457;
const VERSION = 1;

type Src = ByteSource;

type LexFile = {
	src: Src;
	count: number;
	indexAt: number;
	reader: CardReader;
};

function read(src: Src, off: number, len: number): Uint8Array {
	return new Uint8Array(src.readBytes(off, len));
}

function ascii(bytes: Uint8Array, len: number): string {
	if (len <= 0)
		return "";
	if (len > bytes.length)
		len = bytes.length;
	let out = "";
	for (let i = 0; i < len; i++)
		out += String.fromCharCode(bytes[i]);
	return out;
}

/** First key that sorts after every word with this prefix. Null if none. */
function successor(prefix: string): string | null {
	const chars = prefix.split("");
	for (let i = chars.length - 1; i >= 0; i--) {
		if (chars[i] < "z") {
			chars[i] = String.fromCharCode(chars[i].charCodeAt(0) + 1);
			return chars.slice(0, i + 1).join("");
		}
	}
	return null;
}

function parse(src: Src): { count: number; indexAt: number } | null {
	const head = read(src, 0, HEADER);
	if (u32(head) !== MAGIC)
		return null;
	if (u16(head.subarray(4, 6)) !== VERSION)
		return null;
	const count = u16(head.subarray(6, 8));
	const indexAt = u32(head.subarray(8, 12));
	if (indexAt < HEADER)
		return null;
	return { count, indexAt };
}

function tryOpen(): LexFile | null {
	const dir = openCardDir(["cadv", "dict"]);
	if (!dir)
		return null;
	let reader: CardReader | null = null;
	try {
		reader = new CardReader(dir.openFile({ path: "lex.bin", mode: "r" }));
		const header = parse(reader);
		if (!header || reader.failed) {
			reader.close();
			return null;
		}
		return { src: reader, count: header.count, indexAt: header.indexAt, reader };
	}
	catch {
		reader?.close();
		return null;
	}
	finally {
		closeQuiet(dir);
	}
}

let state: LexFile | null | undefined;
/** Bumps when an open lex.bin stops reading (card pulled). */
let lostGeneration = 0;

/*
	A failed read (card pulled) drops the lexicon: counts become 0 and the
	screen shows the no-dictionary state. The next call tries to reopen it
	once, so a reseated card keeps working.
*/
function ensure(): LexFile | null {
	if (state && state.reader.failed) {
		state.reader.close();
		state = undefined;
		lostGeneration += 1;
	}
	if (state !== undefined)
		return state;
	state = tryOpen();
	return state;
}

/** Changes when the lexicon was dropped after a read failure. */
export function lexLost(): number {
	ensure();
	return lostGeneration;
}

export function lexCount(): number {
	const file = ensure();
	return file ? file.count : 0;
}

function record(i: number): Uint8Array | null {
	const file = ensure();
	if (!file || i < 0 || i >= file.count)
		return null;
	return read(file.src, file.indexAt + i * STRIDE, STRIDE);
}

function text(off: number, len: number): string {
	const file = ensure();
	if (!file || len <= 0)
		return "";
	return String.fromArrayBuffer(file.src.readBytes(off, len));
}

export function lexWord(i: number): string {
	const rec = record(i);
	if (!rec)
		return "";
	const len = rec[16];
	if (len <= 0 || len > 16)
		return "";
	return ascii(rec, len);
}

export function lexGloss(i: number): string {
	const rec = record(i);
	if (!rec)
		return "";
	return text(u32(rec.subarray(20, 24)), rec[17]);
}

export function lexPhone(i: number): string {
	const rec = record(i);
	if (!rec)
		return "";
	return text(u32(rec.subarray(24, 28)), rec[18]);
}

/** First index whose word is >= key. count when every word is smaller. */
export function lexLower(key: string): number {
	const n = lexCount();
	let lo = 0;
	let hi = n;
	while (lo < hi) {
		const mid = (lo + hi) >> 1;
		if (lexWord(mid) < key)
			lo = mid + 1;
		else
			hi = mid;
	}
	return lo;
}

/** First index past words that start with prefix. count when prefix is empty. */
export function lexPrefixEnd(prefix: string): number {
	const n = lexCount();
	if (!prefix)
		return n;
	const next = successor(prefix);
	if (next === null)
		return n;
	return lexLower(next);
}
